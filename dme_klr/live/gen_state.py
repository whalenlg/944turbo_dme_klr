#!/usr/bin/env python3
# ============================================================
#  gen_state.py — list every variable of the Verilated model
#
#  Verilator's own checkpointing (--savable) refuses --timing, which
#  the live build needs, so build_live.sh runs this between verilating
#  and compiling. It reads the generated headers in obj/ and writes
#  obj/live_fields.cpp: one liveAdd() call per member variable of each
#  module instance (signals, memories, the ROM arrays, the engine model,
#  Verilator's own edge-detect and NBA temporaries). snapshot.cpp saves
#  and restores those bytes; liveAdd() skips anything that isn't plain
#  data (pointers, the timing schedulers), so nothing here has to know
#  what the design contains.
#
#  Usage: gen_state.py <obj dir> <model prefix, e.g. Vdme_klr_dashboard_tb>
# ============================================================
import re
import sys
from pathlib import Path

obj, prefix = Path(sys.argv[1]), sys.argv[2]


def strip_comments(text):
    return re.sub(r'/\*.*?\*/', '', re.sub(r'//[^\n]*', '', text), flags=re.S)


# Module instances: "Vfoo_bar TOP__a__b;" under MODULE INSTANCE STATE
syms = strip_comments((obj / f'{prefix}__Syms.h').read_text())
instances = re.findall(rf'^\s*({prefix}\w*)\s+(TOP\w*)\s*;', syms, re.M)
if not instances:
    sys.exit(f'gen_state.py: no module instances found in {prefix}__Syms.h')

members = {}   # class -> [member names]
for cls, _ in instances:
    if cls in members:
        continue
    text = strip_comments((obj / f'{cls}.h').read_text())
    body = re.search(rf'class\s+(?:alignas\([^)]*\)\s*)?{cls}\b[^{{]*\{{(.*?)\n\}};', text, re.S)
    if not body:
        sys.exit(f'gen_state.py: class {cls} not found in {cls}.h')
    names = []
    # Braces opened inside the class: 'anon' for the anonymous structs
    # Verilator groups members into (still class scope), 'code' otherwise
    scopes = []
    for line in body.group(1).split('\n'):
        s = line.strip()
        if s in ('struct {', 'union {'):
            scopes.append('anon')
            continue
        if s == '};' and scopes and scopes[-1] == 'anon':
            scopes.pop()
            continue
        # Only declarations at class scope (skip method bodies)
        if all(k == 'anon' for k in scopes):
            m = re.match(r'VL_(?:IN|OUT|INOUT|SIG)\w*\((\w+),', s)
            if m:
                names.append(m.group(1))
            elif (s.endswith(';') and '(' not in s and '=' not in s and 'static' not in s.split()
                  and not s.startswith(('using ', 'friend ', 'typedef ', 'public', 'private', 'protected'))):
                m = re.match(r'(.+?)\s*\b(\w+)\s*;$', s)
                if m and m.group(1).strip() not in ('', 'class', 'struct'):
                    names.append(m.group(2))
        for ch in s:
            if ch == '{':
                scopes.append('code')
            elif ch == '}' and scopes:
                scopes.pop()
    members[cls] = names

out = [
    '// Generated by gen_state.py from the Verilated headers. Do not edit.',
    f'#include "{prefix}__Syms.h"',
    '#include "live_fields.h"',
    '',
    f'void liveFields({prefix}__Syms* s, LiveFieldList& v) {{',
]
for cls, inst in instances:
    for name in members[cls]:
        out.append(f'    liveAdd(v, "{inst}.{name}", s->{inst}.{name});')
out.append('}')
(obj / 'live_fields.cpp').write_text('\n'.join(out) + '\n')
total = sum(len(members[c]) for c, _ in instances)
print(f'gen_state.py: {total} members in {len(instances)} instances')
if total < 100:
    sys.exit(f'gen_state.py: only {total} members found; the Verilated headers in {obj} '
             'are not in a form this script understands, so snapshots would be empty')
